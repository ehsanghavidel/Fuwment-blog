/** مرز چپ واژه‌ی فارسی — تا «باید» داخل «نباید» تطبیق نخورد */
const FA_START = "(?<![\\u0600-\\u06FF\\u200C])";
/** ابزار مقایسه با بازار: بازار، میانگین، صدک، دهک، درصدِ بالا/برتر */
const MARKET = "(?:بازار|میانگین|صدک|دهک|درصد[\\s\\u200C]+(?:بالا|برتر))";
const OBLIGATION = `${FA_START}(?:باید|لازم[\\s\\u200C]+است|لازمه|مجبوری|موظفی)`;
const SPAN = "[^.؟?!؛\\n]";
/**
 * نشانه‌ی **بنچمارک درآمد** — نه هر «بازار». «باید نشان بدهی محصولت بازار
 * دارد» (اینوویتور فاندر) یا «با رقبای بازار مقایسه کن» بنچمارک حقوق نیستند
 * و نباید گرفته شوند. پس یا ابزار آماری (صدک، دهک، میانگین، درصدِ بالا)،
 * یا «بازار» در کنار درآمد/حقوق.
 */
const INCOME_WORD = "(?:درآمد|حقوق|دستمزد)";
const BENCH = `(?:صدک|دهک|میانگین|درصد[\\s\\u200C]+(?:بالا|برتر)|${INCOME_WORD}${SPAN}{0,40}?بازار|بازار${SPAN}{0,40}?${INCOME_WORD})`;

