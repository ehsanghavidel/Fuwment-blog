export type DismissalPattern = { re: RegExp; label: string; safer: string };

/** مرز واژه‌ی فارسی — `\b` جاوااسکریپت روی فارسی کار نمی‌کند */
const NOT_FA = "(?![\\u0600-\\u06FF\\u200C])";

