/**
 * جمله‌هایی که «توصیه‌ی عملی» یا «شاهد ممکن» را با لحن «قاعده‌ی رسمی»
 * می‌گویند، یا خودِ قاب «رسمی» را ادعا می‌کنند.
 *
 * هر الگو یک `support` دارد: آنچه یک فکتِ **رسمیِ سنجیده‌شده** باید درباره‌اش
 * بگوید تا این جمله اصلاً قابل دفاع باشد.
 * - هیچ فکت رسمیِ مرتبطی نیست → مسدودکننده (بازنویسی به توصیه/تفسیر یا حذف)
 * - فکت رسمیِ مرتبط هست → توصیه‌ای (کد نمی‌فهمد جمله «دقیقاً» همان را
 *   می‌گوید یا نه؛ ویراستار و بازبین انسانی می‌سنجند — قاعده‌ی ۲)
 *
 * `support` عمداً سخت‌گیر است جایی که راهنما تمایز را صریح خواسته: GOV.UK
 * (دیجیتال تک) می‌گوید سطح درآمد **یکی از عواملی** است که ممکن است در
 * ارزیابی کلی دیده شود — این «معیار مستقل درآمد» نمی‌سازد. پس الگوی «درآمد
 * … معیار/شاخص است» فقط با فکتی پشتیبانی می‌شود که خودش هم درآمد را
 * «معیار» بنامد.
 */
export type OverclaimPattern = {
  re: RegExp;
  label: string;
  safer: string;
  support: RegExp;
  /**
   * v3.7: آیا همین جمله می‌تواند **توصیف آماری** باشد؟ اگر فکتِ «[آمار رسمی]»
   * مرتبط هست و جمله صراحتاً قاب توصیفی دارد («دارندگان این ویزا»،
   * «گزارش ارزیابی») و هیچ واژه‌ی واجد شرایط بودن ندارد، مجاز است.
   */
  descriptiveOk?: boolean;
};

