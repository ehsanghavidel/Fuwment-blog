/** مرز واژه‌ی فارسی — `\b` جاوااسکریپت روی فارسی کار نمی‌کند (CLAUDE.md قاعده‌ی ۳) */
const FA_LETTER = "[\\u0600-\\u06FF\\u200C]";
/** فاصله یا نیم‌فاصله بین اجزای یک عبارت */
const GAP = "[\\s\\u200C]+";
/** پسوندهای رایجی که به واژه می‌چسبند: «سنجه‌های»، «کژتابی‌ها» */
const SUFFIX = "(?:\\u200C?(?:های|ها|ای|ی|اش|شان|تان))?";

function phrase(words: string[]): RegExp {
  return new RegExp(`(?<!${FA_LETTER})${words.join(GAP)}${SUFFIX}(?!${FA_LETTER})`);
}

