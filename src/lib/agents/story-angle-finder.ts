import "server-only";
import { runAgentJSON } from "@/lib/ai";
import { COMPANY_NAME, COMPANY_PROFILE, BRAND_VOICE } from "@/lib/company";
import { slideText } from "@/lib/slide-spec";
import { lessonsBlockFor } from "./lessons";
import { SocialBriefSchema, type SocialBrief } from "./types";
import type { SocialPost } from "@/lib/store";

/**
 * ایجنت — زاویه‌یاب استوری
 *
 * وظیفه: از یک کاروسلِ **موجود**، دقیقاً یک زاویه را بیرون بکشد که ارزشِ
 * تبدیل‌شدن به یک ستِ ۲ تا ۳ فریمیِ استوری را دارد.
 *
 * چرا این ایجنت با استراتژیست اینستاگرام یا زاویه‌یاب لینکدین فرق دارد؟
 * ماده‌ی خامش نه «مشاهده‌ی خام» است، نه «فهرستِ ایده». یک محتوای کامل و
 * منتشرشده است — کاری که این ایجنت باید بکند «تقطیر» است، نه «اختراع».
 *
 * ⚠️ تصمیمِ معماری: این ایجنت متنِ خامِ کاروسل را می‌بیند، ولی خروجی‌اش
 * `SocialBrief` است — همان قراردادِ پلتفرم‌خنثیِ بقیه‌ی پایپ‌لاین‌ها.
 * کپی‌رایترِ استوری (مرحله‌ی بعد) فقط همین بریف را می‌بیند، نه متنِ خامِ
 * کاروسل را. این جداییِ **ساختاری** است، نه یک قاعده‌ی پرامپتی: تا وقتی
 * کپی‌رایتر اصلاً به جمله‌های کاروسلِ مبدأ دسترسی ندارد، «کپیِ عینیِ
 * جمله‌ها» به‌جای تکرار در پرامپت، از معماری غیرممکن می‌شود.
 */
export async function runStoryAngleFinder(input: {
  /** کاروسلِ منتشرشده‌ای که استوری از آن مشتق می‌شود */
  source: SocialPost;
}): Promise<SocialBrief> {
  const { source } = input;
  const lessons = await lessonsBlockFor("story-angle-finder");

  const system = `تو «زاویه‌یاب استوری» ${COMPANY_NAME} هستی. کارت این است که از یک کاروسلِ اینستاگرامِ کامل و موجود، دقیقاً **یک** زاویه را انتخاب کنی که ارزشِ تبدیل‌شدن به یک ستِ کوتاهِ استوری را دارد.

${COMPANY_PROFILE}

${BRAND_VOICE}

قواعد:
- استوری **خلاصه‌ی فشرده‌ی کاروسل نیست**. اگر همه‌ی نکته‌های کاروسل را در حجم کوچک‌تر تکرار کنی، شکست خورده‌ای. باید یک زاویه‌ی واحد و برنده را انتخاب کنی — همانی که به‌تنهایی هم برای کسی که کاروسل را ندیده، ارزشِ دیدن دارد.
- coreMessage باید همان یک زاویه باشد، نه چکیده‌ی کل کاروسل.
- keyPoints باید «ادعا» باشند، نه تیترِ اسلایدهای کاروسل.
- hookAngle باید طوری نوشته شود که **بدونِ دیدنِ کاروسلِ مبدأ** هم قابلِ فهم باشد و کنجکاوی بسازد — استوری تمام‌صفحه دیده می‌شود، نه در کنار کاروسل.
- proofPoint باید از دلِ همین کاروسل بیاید، نه ساخته‌ی خودت.
- **هیچ عدد، آمار یا ادعایی که در متنِ کاروسل نیست از خودت نساز.**
- بریف را پلتفرم‌خنثی بنویس؛ کپی‌رایترِ استوری خودش لباسِ استوری را می‌پوشاند و اصلاً متنِ کاروسل را نمی‌بیند — پس هرچه لازم است از کاروسل منتقل شود، باید در همین بریف باشد.

⚠️ **بریف، کپیِ قابلِ استفاده نیست — یادداشتِ مفهومی برای یک نویسنده‌ی دیگر است.**
تو تنها کسی هستی که متنِ خامِ کاروسل را می‌بیند. کپی‌رایترِ استوری فقط بریفِ تو را می‌خواند، پس هرچه در بریف عیناً از کاروسل بماند، عیناً در استوری هم سر برمی‌آورد — این خودِ نشتیِ کپی است، نه چیزی که در مرحله‌ی بعد قابلِ اصلاح باشد.
- معنا و شاهد را منتقل کن، نه جمله‌بندیِ کاروسل را. اسکلتِ جمله، ترتیب و لحنِ بولت‌ها، و عنوانِ اسلایدها را عیناً به بریف نیاور.
- keyPoints و proofPoint را به‌صورتِ **یادداشتِ مفهومیِ سطح‌بالا** بنویس — چیزی که نویسنده باید از نو با کلمات و ساختارِ خودش بیان کند، نه جمله‌ای که می‌شود مستقیم در فریم چسباند.
- لازم نیست ترتیبِ بولت‌های کاروسل را حفظ کنی، مگر ترتیبِ واقعیِ رویدادها/مراحل الزامش کند.
- فقط عوض‌کردنِ چند کلمه با مترادف کافی نیست — این باز هم همان جمله‌ی کاروسل شمرده می‌شود. ساختار و زاویه‌ی بیان باید واقعاً فرق کند.
- نامِ رسمیِ مسیرها (مثلاً Global Talent، Innovator Founder)، اصطلاحاتِ فنی/حقوقیِ ضروری، و اعداد/شواهدِ واقعی را دقیقاً همان‌طور نگه دار — این‌ها اصطلاحِ لازم‌اند، نه کپی.${lessons}`;

  const carouselBlock = `کاروسلِ مبدأ — «${source.title}»:
کپشن: ${source.body}

اسلایدها:
${source.slides.map((s, i) => `${i + 1}. ${slideText(s)}`).join("\n")}`;

  const prompt = `${carouselBlock}

از این کاروسل، یک بریفِ اجتماعی برای یک ستِ استوریِ ۲ تا ۳ فریمی بساز.`;

  const result = await runAgentJSON({
    agent: "story-angle-finder",
    system,
    prompt,
    temperature: 0.5,
    schema: SocialBriefSchema,
    shapeHint: `{
  "coreMessage": "همان یک زاویه‌ی برنده از دلِ کاروسل",
  "audience": "مخاطب مشخص این استوری",
  "keyPoints": ["ادعای مستقل اول", "ادعای دوم"],
  "hookAngle": "قلابی که بدونِ دیدنِ کاروسل هم می‌ایستاند",
  "proofPoint": "شاهد/جزئیاتِ ملموس، از دلِ همین کاروسل",
  "cta": "دعوت به اقدامِ فریمِ آخر"
}`,
  });

  // زبانِ استوری همانِ زبانِ کاروسلِ مبدأ است — تصمیمِ اجراست، نه قضاوتِ مدل.
  return { ...result, language: source.language };
}
