  // ⚠️ استوری کپشن ندارد؛ «hook» یعنی تیترِ فریمِ ۰، نه جمله‌ی اولِ کپشن.
  story: `- hook: آیا تیترِ فریمِ ۰ به‌تنهایی، بدونِ دیدنِ کاروسلِ مبدأ، اسکرول را متوقف می‌کند؟
- platformFit: آیا واقعاً یک ستِ استوری است؟ فریم‌ها یک مینی‌روایتِ واحد می‌سازند (قلاب → [بدنه] → دعوت)، هیچ فریمی حرفِ فریمِ دیگر یا کاروسلِ مبدأ را عیناً تکرار نمی‌کند، و متنِ هر فریم برای خواندنِ چندثانیه‌ای روی تمام‌صفحه به‌اندازه‌ی کافی کوتاه است.`,
