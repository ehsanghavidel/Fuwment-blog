const CHANNEL_LABEL: Record<SocialChannel, string> = {
  instagram: "کاروسل اینستاگرام",
  linkedin: "پست لینکدین",
  reels: "اسکریپت ریلز",
  story: "ستِ استوری اینستاگرام",
};

export async function runSocialEditor(input: {
  channel: SocialChannel;
  brief: SocialBrief;
  draft: unknown;
  failedChecks: SocialCheck[];
}): Promise<SocialReview> {
  const lessons = await lessonsBlockFor("social-editor");
  const label = CHANNEL_LABEL[input.channel];

  const system = `تو «ویراستار شبکه‌های اجتماعی» ${COMPANY_NAME} هستی — سخت‌گیر اما منصف. کارت قضاوت کیفیت است، نه بازنویسی. ایرادهایی که می‌گیری باید آن‌قدر مشخص باشند که کپی‌رایتر دقیقاً بداند چه چیزی را کجا عوض کند.
${input.brief.language === "en" ? `
⚠️ زبان خروجی این محتوا **انگلیسی** است و این یک تصمیم است، نه اشتباه. هرگز پیشنهاد نکن که به فارسی برگردانده شود و هرگز انگلیسی‌بودن را در issues نیاور. قواعد نگارش فارسی — نیم‌فاصله، ارقام فارسی، گیومه‌ی فارسی — اینجا اصلاً موضوعیت ندارند.
` : ""}
${BRAND_VOICE}${lessons}`;

  const prompt = `بریف اجتماعی:
پیام مرکزی: ${input.brief.coreMessage}
مخاطب: ${input.brief.audience}
زاویه‌ی قلاب: ${input.brief.hookAngle}

— ${label} برای بازبینی —
${JSON.stringify(input.draft, null, 2)}

— چک‌های قطعیِ ردشده (کد اندازه گرفته، دوباره قضاوتشان نکن) —
${input.failedChecks.map((c) => `- ${c.name}: ${c.note}`).join("\n") || "- (همه پاس شدند)"}

این محتوا را با روبریک زیر ارزیابی کن (هر معیار ۰ تا ۱۰):
${CHANNEL_RUBRIC[input.channel]}
- brandVoice: تطابق با لحن برند — بدون اغراق، بدون تبلیغ‌زدگی، بدون ادبیات ترس و نجات؟ ⚠️ اداری‌بودن اینجا سنجیده نمی‌شود؛ آن معیار persian است. متنی می‌تواند کاملاً غیرتبلیغاتی و در عین حال کاملاً بی‌جان باشد — اینجا نمره‌ی کاملش را بده و جریمه‌اش را در persian اعمال کن.
- clarity: آیا پیام مرکزی روشن منتقل شده یا در کلی‌گویی گم شده؟
- persian: ${LIVENESS_CRITERION[input.brief.language === "en" ? "en" : "fa"]}

score = مجموع پنج معیار × ۲ (یعنی ۰ تا ۱۰۰).
اگر score زیر ${SOCIAL_APPROVE_THRESHOLD} بود verdict را "revise" بگذار و در issues دقیق بگو چه چیزی باید اصلاح شود؛ وگرنه "approve".
حتی وقتی verdict را "approve" می‌گذاری، اگر معیاری زیر ۷ گرفت دلیلش را در issues بنویس. issues خودش بازنویسی راه نمی‌اندازد؛ فقط به بازبین انسانی نشان می‌دهد کجا ضعیف بوده.`;

  return runAgentJSON({
    agent: "social-editor",
    system,
    prompt,
    temperature: 0.3,
    schema: SocialReviewSchema,
    shapeHint: `{
  "score": 78,
  "rubric": { "hook": 8, "platformFit": 8, "brandVoice": 8, "clarity": 7, "persian": 8 },
  "issues": ["ایراد مشخص و قابل اجرا"],
  "verdict": "approve"
}`,
  });
}
