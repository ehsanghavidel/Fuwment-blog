import "server-only";
import { runAgentJSON } from "@/lib/ai";
import { BRAND_VOICE, COMPANY_NAME, COMPANY_PROFILE } from "@/lib/company";
import { lessonsBlockFor } from "./lessons";
import { BriefSchema, type Brief, type Idea } from "./types";
import { ctaListBlock, allowedCtaIds } from "./brand-cta";
import type { BrandRoute } from "@/lib/company";

/** توصیف هر مسیر برای پرامپت — همان تفکیکی که در COMPANY_PROFILE آمده */
const ROUTE_BRIEFING: Record<BrandRoute, string> = {
  brand:
    "سطح برند — نسبت به دو مسیر بی‌طرف بمان و هیچ‌کدام را پیش‌فرض نگیر. مقاله باید به مخاطب کمک کند خودش را بسنجد، نه اینکه او را به یک مسیر خاص هل بدهد.",
  "global-talent":
    "Global Talent — بر پایه‌ی دستاورد و تاثیر فردی. محتوا حول شواهد، تاثیر و رهبری فردی می‌چرخد.",
  "innovator-founder":
    "Innovator Founder — بر پایه‌ی ایده و کسب‌وکار، با سه معیار رسمی نوآورانه · قابل‌اجرا · مقیاس‌پذیر.",
};

/**
 * ایجنت ۲ — استراتژیست محتوا (Content Strategist)
 *
 * وظیفه: تبدیل بهترین ایده به «بریف محتوا» — سندی که نویسنده و سئوکار
 * بر اساس آن کار می‌کنند: مخاطب دقیق، کلمه‌ی کلیدی اصلی، ساختار مقاله و CTA.
 *
 * نکته‌ی آموزشی: جداکردن «تصمیم‌گیری درباره‌ی چیستی» (استراتژیست) از
 * «تولید» (نویسنده) کیفیت را بالا می‌برد؛ همان دلیلی که در تیم انسانی هم
 * بریف قبل از نوشتن تهیه می‌شود.
 */

export async function runStrategist(input: {
  ideas: Idea[];
  topicHint: string | null;
  /** مسیر برند — انسان در استودیو انتخابش کرده، مدل تصمیم‌گیرنده‌اش نیست */
  route: BrandRoute;
}): Promise<Brief> {
  const lessons = await lessonsBlockFor("strategist");

  const system = `تو «استراتژیست محتوا»ی شرکت ${COMPANY_NAME} هستی. از بین ایده‌ها بهترین را انتخاب و به بریف اجرایی تبدیل می‌کنی.

${COMPANY_PROFILE}

${BRAND_VOICE}${lessons}`;

  const ideasText = input.ideas
    .map(
      (i, n) =>
        `${n + 1}. «${i.title}» (امتیاز ${i.score}/10)\n   زاویه: ${i.angle}\n   نیت جستجو: ${i.searchIntent}`
    )
    .join("\n");

  const prompt = `ایده‌های پیشنهادی ایده‌یاب (مرتب بر اساس امتیاز):

${ideasText}

بهترین ایده را انتخاب کن (لازم نیست حتماً اولی باشد — قضاوت خودت را داشته باش) و بریف کامل محتوا بساز:
- عنوان نهایی را در صورت نیاز بهتر کن (جذاب اما بدون کلیک‌بیت).
- کلمه‌ی کلیدی اصلی باید عبارتی باشد که واقعاً به فارسی جستجو می‌شود.

— هدف‌گیری —
مسیر این مقاله **از قبل تعیین شده** و تصمیم تو نیست:
route = "${input.route}" → ${ROUTE_BRIEFING[input.route]}
همین مقدار را عیناً در فیلد route بگذار و کل بریف را با همین مسیر هم‌خوان کن.

— دو تصمیم دیگر (هر دو اجباری، و «همه» جواب مجاز نیست) —
- audienceGroup: کدام‌یک از پنج گروه؟
  digital-tech (مهندس نرم‌افزار، دیزاینر محصول، متخصص داده، مدیر محصول) ·
  academic-research (دکترا، پسادکترا، هیئت علمی) ·
  arts-culture (فیلم‌ساز، طراح، نویسنده، موسیقی‌دان، کیوریتور) ·
  engineering-medical (مهندسی، پزشکی و پژوهش بالینی) ·
  entrepreneurship (بنیان‌گذار استارتاپ یا کسب‌وکار فعال)
- journeyStage: مخاطب این مقاله کجای سفر است؟
  · unaware — نمی‌داند این مسیرها وجود دارند یا فکر می‌کند برای نوابغ‌اند.
    محتوای این مرحله نباید بفروشد.
  · curious — می‌داند مسیر هست و می‌پرسد «من هم می‌توانم؟»
  · evaluating — دارد می‌سنجد به چه کسی اعتماد کند.
  · decision — می‌پرسد ارزش هزینه‌اش را دارد یا نه.
  · in-journey — در مسیر است و می‌خواهد بداند کجای کار است.
  · success — مسیر را طی کرده؛ محتوای استقرار و روایت تجربه.
  · referral — راضی است و می‌تواند دیگران را معرفی کند.
  برای مقاله‌ی بلاگ معمولاً یکی از چهار مرحله‌ی اول درست است.
- فیلد audience را متناسب با همان گروه بنویس، مشخص و ملموس. «همه‌ی متخصصان»
  یا «عموم مخاطبان» رد می‌شود؛ محتوایی که برای همه نوشته شود قلاب ندارد.
- ساختار (outline) باید ۴ تا ۷ بخش داشته باشد و آخرین بخش به یک قدم بعدی روشن برسد.
- طول هدف بین ۹۰۰ تا ۱۵۰۰ کلمه باشد.

— دعوت به اقدام —
${ctaListBlock(input.route)}

از فهرست بالا **دقیقاً یکی** را انتخاب کن و شناسه‌اش را در ctaId بگذار.
در فیلد cta همان دعوت را با لحن برند و متناسب با موضوع مقاله بنویس (یکی دو
جمله) — برچسب فهرست یک نام است، نه متنی که باید عیناً نقل شود.
مرحله‌ی سفر مخاطب را در انتخابت لحاظ کن: در unaware و curious معمولاً دعوت
واسط درست‌تر است، چون محتوای این مراحل نباید بفروشد.
عبارت «مشاوره‌ی رایگان» ممنوع است؛ آن خدمت وجود ندارد.`;

  const brief = await runAgentJSON({
    agent: "strategist",
    system,
    prompt,
    schema: BriefSchema,
    shapeHint: `{
  "title": "عنوان نهایی مقاله",
  "audience": "توصیف دقیق مخاطب این مقاله",
  "route": "${input.route}",
  "audienceGroup": "digital-tech",
  "journeyStage": "unaware",
  "searchIntent": "نیت جستجوی کاربر",
  "primaryKeyword": "کلمه کلیدی اصلی فارسی",
  "secondaryKeywords": ["کلمه ۱", "کلمه ۲", "کلمه ۳"],
  "outline": [
    { "heading": "عنوان بخش", "points": ["نکته‌ای که باید پوشش داده شود"] }
  ],
  "targetWordCount": 1200,
  "cta": "متن دعوت به اقدام پایانی در یکی دو جمله",
  "ctaId": "${allowedCtaIds(input.route)[0]}"
}`,
  });

  // مسیر تصمیم انسان است، نه مدل. حتی با وجود تأکید در پرامپت و shapeHint،
  // بازتاب درستِ یک مقدار ثابت چیزی نیست که به مدل بسپاریم — همان اصلِ
  // «کار قطعی را به مدل نسپار» که در clampText و یکتاسازی اسلاگ هم هست.
  return { ...brief, route: input.route };
}
