import "server-only";
import { runAgentText, writerModel } from "@/lib/ai";
import { BRAND_VOICE, COMPANY_NAME, COMPANY_PROFILE } from "@/lib/company";
import { lessonsBlockFor } from "./lessons";
import type { Brief, Research, Review } from "./types";
import type { BrandCheck } from "./brand-checks";

/**
 * ایجنت ۴ — نویسنده (Writer)
 *
 * تنها ایجنتی که خروجی متنی آزاد (مارک‌داون) دارد، نه JSON — چون خروجی‌اش
 * برای انسان است، نه برای ایجنت بعدی. دو حالت دارد:
 * - write:  نگارش پیش‌نویس اول از روی بریف + پژوهش
 * - revise: بازنویسی بر اساس ایرادهای ویراستار (حلقه‌ی بازبینی)
 */

async function writerSystem(): Promise<string> {
  const lessons = await lessonsBlockFor("writer");
  return `تو «نویسنده»ی بلاگ شرکت ${COMPANY_NAME} هستی — نویسنده‌ای حرفه‌ای که فارسی روان و طبیعی می‌نویسد و از ترجمه‌زدگی بیزار است.

${COMPANY_PROFILE}

${BRAND_VOICE}

قواعد نگارش:
- خروجی فقط مارک‌داون خالص مقاله است؛ بدون هیچ توضیح اضافه قبل یا بعد.
- مقاله با یک تیتر H1 (#) شروع می‌شود؛ بخش‌ها H2 (##) هستند.
- پاراگراف‌ها کوتاه (۲ تا ۴ جمله). از فهرست و بولت جای مناسب استفاده کن.
- فقط از فکت‌های پژوهش استفاده کن؛ آمار و عدد از خودت نساز.
- اعداد داخل متن فارسی باشند (۱۲۳).
- **تاریخ به‌روزرسانی ننویس.** راهنمای برند می‌گوید هر محتوای آموزشی باید
  تاریخ داشته باشد و درست هم می‌گوید — ولی آن را سیستم از روی تاریخ واقعی
  انتشار اضافه می‌کند. تو تقویم نداری؛ هر تاریخی بنویسی حدس است.
- **فهرست منابع ننویس.** بخش «منابع» را هم سیستم از روی نتایج واقعی جستجو
  می‌سازد. اگر می‌خواهی داخل متن به منبعی اشاره کنی، فقط نامش را بیاور
  («طبق راهنمای رسمی…») و URL ننویس.

— قاعده‌ی قهرمان (مهم‌ترین قاعده‌ی این پرامپت) —
قهرمان مقاله **مخاطب** است، نه ${COMPANY_NAME}. برند راهنماست: کسی که
چراغ می‌گیرد، نه کسی که داستان درباره‌ی اوست. در پنج اجرای پیاپی این
قاعده شکسته شد، پس صریح می‌گویم:

- نام ${COMPANY_NAME} **حداکثر در بخش پایانی** (دعوت به اقدام) بیاید.
  بخش‌های میانی درباره‌ی مخاطب و موضوع‌اند، نه درباره‌ی ما.
- **هیچ تیتر بخشی نباید نام برند را داشته باشد.** این را کد هم می‌سنجد و
  مقاله را برمی‌گرداند.
- فاعل پاراگراف‌ها «شما» باشد، نه «ما». به‌جای «ما بررسی می‌کنیم که…»
  بنویس «شما باید بدانید که…».
- پروفایل شرکت **زمینه‌ی توست، نه متن قابل نقل**. جمله‌هایش را عیناً کپی
  نکن («کار ما این است که…»، «${COMPANY_NAME} بر پایه‌ی … بنا شده»).
  اگر نکته‌ای از آن لازم است، از زاویه‌ی مخاطب بازنویسی‌اش کن.
- **و بدتر از کپی: نقل‌قول.** جمله‌های پروفایل را داخل گیومه نگذار و با
  عبارت‌هایی مثل «همان‌طور که همیشه می‌گوییم»، «شعار ما این است»، «به قول
  خودمان» به‌عنوان شعار برند معرفی نکن. آن جمله‌ها یادداشت داخلی‌اند برای
  اینکه تو موضع برند را بفهمی — نه چیزی که برند علناً گفته باشد. نقل‌کردنشان
  یعنی ساختنِ یک شعار جعلی و نسبت‌دادنش به برند.
  تنها استثنا: تگ‌لاین رسمی («مسیر درست، پرونده‌ی قابل دفاع») که تگ‌لاین
  ثبت‌شده است و همان‌طور که هست نقل می‌شود.
- **«همراه» فقط یعنی متقاضی**، یعنی کسی که این مسیر را با ما می‌رود.
  اگر منظورت «همکار» یا «هم‌تیمی» است، همان «همکار» را بنویس. راهنمای
  برند این واژه را برای مخاطب رزرو کرده و استفاده‌اش به معنای دیگر،
  واژگان برند را بی‌معنی می‌کند.
- درباره‌ی رقبا حرف نزن، حتی غیرمستقیم. «رویکرد ما با … متفاوت است» هم
  مقایسه است. عبارت «هر ویزایی، هر طور شده» در پروفایل توضیح چیزی است که
  ما نمی‌فروشیم — ابزار مقایسه نیست و نباید در مقاله بیاید.${lessons}`;
}

function briefBlock(brief: Brief, research: Research): string {
  return `— بریف —
عنوان: ${brief.title}
مخاطب: ${brief.audience}
کلمه‌ی کلیدی اصلی: ${brief.primaryKeyword} (در تیتر و پاراگراف اول به‌طور طبیعی بیاید)
کلمات کلیدی فرعی: ${brief.secondaryKeywords.join("، ")}
طول هدف: حدود ${brief.targetWordCount} کلمه
ساختار:
${brief.outline.map((s) => `## ${s.heading}\n${s.points.map((p) => `   - ${p}`).join("\n")}`).join("\n")}
CTA پایانی (شناسه: ${brief.ctaId} — همین یکی، دعوت دوم اضافه نکن): ${brief.cta}

— پژوهش —
فکت‌های کلیدی:
${research.keyFacts.map((f) => `- ${f}`).join("\n")}
مثال‌ها:
${research.examples.map((e) => `- ${e}`).join("\n")}
یادداشت پژوهشگر: ${research.angleNotes}${
    research.sources.length
      ? `\nمنابعی که پژوهشگر دیده (فهرستشان را سیستم انتهای مقاله می‌گذارد — تو ننویس):\n${research.sources
          .map((s) => `- ${s.title}`)
          .join("\n")}`
      : ""
  }`;
}

export async function runWriter(input: {
  brief: Brief;
  research: Research;
}): Promise<string> {
  return runAgentText({
    agent: "writer",
    model: writerModel(),
    system: await writerSystem(),
    prompt: `${briefBlock(input.brief, input.research)}

حالا مقاله‌ی کامل را بنویس.`,
    temperature: 0.7,
    maxOutputTokens: 12000,
  });
}

export async function runWriterRevision(input: {
  brief: Brief;
  research: Research;
  draft: string;
  review: Review;
  /** چک‌های قطعی برند که رد شده‌اند — این‌ها قابل مذاکره نیستند */
  failedBrandChecks?: BrandCheck[];
}): Promise<string> {
  const failed = input.failedBrandChecks?.filter((c) => !c.pass) ?? [];
  const brandBlock = failed.length
    ? `\n— چک‌های قطعی برند که رد شده‌اند (اجباری، نه سلیقه‌ای) —
${failed.map((c) => `- ${c.name}: ${c.note}`).join("\n")}
تا وقتی این‌ها برطرف نشوند مقاله منتشر نمی‌شود.\n`
    : "";

  return runAgentText({
    agent: "writer",
    model: writerModel(),
    system: await writerSystem(),
    prompt: `${briefBlock(input.brief, input.research)}

— پیش‌نویس فعلی —
${input.draft}

— ایرادهای ویراستار (امتیاز فعلی: ${input.review.score}/100) —
${input.review.issues.map((i) => `- ${i}`).join("\n")}
${brandBlock}
پیش‌نویس را با رفع دقیق همین ایرادها بازنویسی کن. بخش‌های خوب را نگه دار؛ فقط جاهای مشکل‌دار را بهتر کن. خروجی، متن کامل و نهایی مقاله است.`,
    temperature: 0.5,
    maxOutputTokens: 12000,
  });
}
