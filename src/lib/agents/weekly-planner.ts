import "server-only";
import { runAgentJSON } from "@/lib/ai";
import { COMPANY_NAME, COMPANY_PROFILE } from "@/lib/company";
import { lessonsBlockFor } from "./lessons";
import { ROUTE_BRIEFING } from "./brand-cta";
import { CONTENT_TYPE_BRIEFING, WEEKLY_GRID } from "./weekly-grid";
import { JOURNEY_STAGES, WeeklyPlanSchema, type WeeklyPlan } from "./types";

/**
 * ایجنت ۱ (پایپ‌لاین هفتگی) — برنامه‌ریز هفتگی
 *
 * یک فراخوانی مدل، یک برنامه‌ی هفت‌اسلاتی. جایگزین هفت ایده‌یابِ مستقل.
 *
 * ── چرا این ایجنت وجود دارد ──
 *
 * تا پیش از این، هر اجرای اینستاگرام خودش ایده تولید می‌کرد. برای اجرای
 * دستی درست است، ولی برای هفت اجرای موازی دو مشکل دارد:
 *
 * ۱. هر هفت اجرا `listSocialPosts` را در یک لحظه می‌خوانند، پس همه همان
 *    فهرست را می‌بینند و **هیچ‌کدام کار دیگری را نمی‌بیند**. مکانیزم
 *    ضدتکرارِ ایده‌یاب بین اجراهای هم‌زمان کاملاً کور است.
 * ۲. ایده‌یاب با دمای ۰٫۹ کار می‌کند و هیچ‌یک از چهار معیار امتیازدهی‌اش
 *    به وفاداری به موضوع امتیاز نمی‌دهد — دو تایشان («قلاب قوی‌تر»،
 *    «حرف تازه‌تر») صریحاً خلافش را پاداش می‌دهند.
 *
 * تمایز، یک ویژگی در سطح **مجموعه** است. هفت ایجنت مستقل که هرکدام محلی
 * بهینه می‌کنند نمی‌توانند تضمینش کنند؛ یک ایجنت که کل شبکه را می‌بیند
 * می‌تواند. همان استدلالِ `campaign-strategist`.
 *
 * ── مرز مسئولیت ──
 *
 * زبان، مسیر، گروه مخاطب و نوع محتوا **پرسیده نمی‌شوند**. از WEEKLY_GRID
 * می‌آیند و به‌عنوان محدودیتِ داده‌شده تزریق می‌شوند. دلیلش در weekly-grid.ts
 * نوشته شده: نسبت ۷۰/۲۰/۱۰ برندگاید فقط وقتی تضمین‌شده است که ساختاری
 * باشد، نه انتخابی. همان الگوی ROUTE_BRIEFING در instagram-strategist.ts.
 *
 * مدل فقط چهار چیز می‌سازد: journeyStage، topic، hook، painPoint.
 */

/** بازه‌ی حافظه‌ی تکرار — سه ماه اخیر */
export const RECENT_TITLES_DAYS = 90;

/**
 * حداقل تعداد مرحله‌ی متمایز سفر در یک هفته.
 *
 * هم در پرامپت تزریق می‌شود هم در چک قطعی سنجیده — یک عدد، یک منبع.
 * اگر دو جا نوشته می‌شد، اولین تغییر یکی را جا می‌گذاشت و چک با قاعده
 * ناهم‌خوان می‌شد بی‌آنکه کسی بفهمد.
 */
export const MIN_DISTINCT_JOURNEY_STAGES = 4;

/** توضیح یک‌خطی هر گروه مخاطب، برای اینکه برنامه‌ریز قلاب درست را بردارد */
const AUDIENCE_BRIEFING: Record<string, string> = {
  "digital-tech":
    "دیجیتال تک — تاثیر ساخته ولی فکر می‌کند تاثیر «مدرک» نیست. خودکم‌بینی بیشترین است.",
  "academic-research":
    "آکادمیک و پژوهش — مدرک کم ندارد، مسیر را نمی‌بیند. لحن دقیق‌تر و داده‌محورتر.",
  "arts-culture":
    "هنر و فرهنگ — دستاوردش پراکنده است و باور دارد این مسیرها برای مهندس و پزشک ساخته شده‌اند.",
  "engineering-medical":
    "مهندسی و پزشکی — نگرانی اصلی هزینه‌ی فرصت است. ماهیت پژوهشی فعالیت تعیین‌کننده است، نه عنوان شغلی.",
  entrepreneurship:
    "کارآفرینی — بین دو مسیر گیر کرده و می‌ترسد ایده‌اش قضاوت شود.",
};

/**
 * شبکه، به‌شکل خوانا برای مدل.
 *
 * ⚠️ `day` عمداً در متن می‌آید و اسکیما هم می‌گیردش: خروجی باید بتواند به
 * اسلاتِ خودش گره بخورد. بدون آن، هفت شیء بی‌هویت داریم و ترتیب آرایه
 * تنها بند نجات است — که قرارداد شکننده‌ای است.
 */
function gridBlock(): string {
  return WEEKLY_GRID.map((slot) => {
    const audience = slot.audienceGroup
      ? AUDIENCE_BRIEFING[slot.audienceGroup] ?? slot.audienceGroup
      : "بدون گروه مخاطب مشخص — مخاطب انگلیسی‌زبان: نهاد، دانشگاه، شریک بین‌المللی";

    return `day=${slot.day} (${slot.dayLabel})
  زبان: ${slot.language === "fa" ? "فارسی" : "انگلیسی"}
  مسیر: ${slot.route} → ${ROUTE_BRIEFING[slot.route]}
  گروه مخاطب: ${audience}
  نوع محتوا: ${CONTENT_TYPE_BRIEFING[slot.contentType]}`;
  }).join("\n\n");
}

export async function runWeeklyPlanner(input: {
  /** عنوان محتواهای ۹۰ روز اخیر — حافظه‌ی تکرار */
  recentTitles: string[];
  /** شنبه‌ی این هفته، فقط برای زمینه‌دادن به مدل */
  weekStart: string;
}): Promise<WeeklyPlan> {
  // ⚠️ بدون این خط، منتقد درس تولید و ذخیره می‌کند، درس در استودیو هم
  // دیده می‌شود، ولی هیچ‌وقت به هیچ پرامپتی تزریق نمی‌شود. حلقه‌ی
  // خودبهبودی نیمه‌کاره می‌ماند و هیچ خطایی هم نمی‌دهد.
  const lessons = await lessonsBlockFor("weekly-planner");

  const system = `تو «برنامه‌ریز محتوای هفتگی» ${COMPANY_NAME} هستی. یک هفته‌ی کامل محتوای اینستاگرام را طراحی می‌کنی — هفت پست، یکی برای هر روز.

${COMPANY_PROFILE}

کارِ تو **طراحی در سطح هفته** است، نه نوشتن هفت ایده‌ی مستقل. هفت پستی که هرکدام جداگانه خوب باشند ولی کنار هم تکراری یا بی‌ربط بیایند، هفته‌ی بدی است. چیزی که فقط تو می‌توانی تضمین کنی و هیچ ایجنت پایین‌دستی نمی‌تواند، همین انسجام و تمایز است.

── محدودیت‌های داده‌شده ──

زبان، مسیر، گروه مخاطب و نوع محتوای هر روز **از قبل تعیین شده‌اند و انتخاب تو نیستند**. اینها پیکربندی برند‌ند و نسبت محتوای هفته را تضمین می‌کنند. آنها را عوض نکن، جابه‌جا نکن، و در خروجی هم برنگردان.

تنها چهار چیز را تو می‌سازی: journeyStage، topic، hook، painPoint.

── قواعد سخت ──

۱. **هفت موضوع باید کاملاً متمایز باشند.** نه هفت زاویه از یک موضوع، نه یک موضوع با هفت عنوان. اگر دو اسلات را بشود جای هم گذاشت، برنامه آماده نیست. تمایز واقعی یعنی مخاطبی که هر هفت روز را ببیند، هفت چیز متفاوت یاد بگیرد.

۲. **journeyStage باید در طول هفته توزیع شود.** هفت مرحله موجود است: ${JOURNEY_STAGES.join("، ")}. حداقل ${MIN_DISTINCT_JOURNEY_STAGES} مرحله‌ی متفاوت در هفته بیاور. هفته‌ای که همه‌ی اسلات‌هایش «curious» باشند، یک هفته نیست — یک پست است که هفت بار تکرار شده.
   و مرحله باید با نوع محتوا هم‌خوان باشد: محتوای آموزشی معمولاً مراحل ابتدایی (unaware، curious) را هدف می‌گیرد و محتوای فروش مستقیم مراحل پایانی (decision) را. محتوای مرحله‌ی آگاهی نباید بفروشد.

۳. **topic باید یک موضوع مشخص باشد، نه یک حوزه.** «شواهد در گلوبال تلنت» یک حوزه است و بی‌مصرف. «چرا توصیه‌نامه‌ی مدیر مستقیم ضعیف‌ترین شاهد پرونده است» یک موضوع است.

۴. **hook همان جمله‌ای است که اسکرول را متوقف می‌کند** — درد مخاطب، نه عنوان موضوع. با نام برند شروع نکن.

۵. **painPoint باید سطح درونی مشکل را بگوید، نه فقط بیرونی.** «نمی‌داند چه چیزی مدرک حساب می‌شود» بیرونی است. «ماه‌هاست بین اطلاعات ضدونقیض می‌چرخد و ته ذهنش می‌گوید شاید من خاص نیستم» درونی است — و همان است که آدم را متوقف می‌کند.

۶. **هیچ عدد، درصد یا آماری نساز.** اگر عددی در پروفایل شرکت نیست، وجود ندارد.${lessons}`;

  const recent =
    input.recentTitles.length > 0
      ? `\n\n— محتواهای ${RECENT_TITLES_DAYS} روز اخیر —\nهیچ موضوعی از این فهرست و هیچ چیز نزدیک به آن تکرار نشود:\n${input.recentTitles.map((t) => `- ${t}`).join("\n")}`
      : `\n\n(محتوای قبلی‌ای در ${RECENT_TITLES_DAYS} روز اخیر نیست — دست تو بازتر است.)`;

  const prompt = `هفته‌ی شروع‌شده از ${input.weekStart} (شنبه) را برنامه‌ریزی کن.

— شبکه‌ی هفته —

${gridBlock()}${recent}

برای هر هفت اسلات، journeyStage و topic و hook و painPoint بنویس. فیلد day را دقیقاً همان عددی بگذار که در شبکه آمده.`;

  const plan = await runAgentJSON({
    agent: "weekly-planner",
    system,
    prompt,
    // پایین‌تر از ایده‌یاب (۰٫۹): اینجا واگرایی لازم نیست، انسجام لازم است.
    // بالاتر از استراتژیست (۰٫۴): هنوز کار خلاقانه است، نه تبدیل قالب.
    temperature: 0.7,
    schema: WeeklyPlanSchema,
    shapeHint: `{
  "slots": [
    {
      "day": 0,
      "journeyStage": "curious",
      "topic": "موضوع مشخص این روز — نه یک حوزه",
      "hook": "جمله‌ای که اسکرول را متوقف می‌کند",
      "painPoint": "درد مخاطب، در سطح درونی"
    }
  ]
}`,
  });

  /**
   * چک قطعی: توزیع مرحله‌ی سفر.
   *
   * «آیا هفت موضوع متمایزند؟» یک قضاوت است و چک قطعی برایش ابزار غلطی
   * است. ولی «چند مرحله‌ی متفاوت آمده؟» یک شمارش است — دقیقاً همان
   * مرزی که brand-checks.ts هم رعایت می‌کند.
   *
   * ⚠️ **هشدار است، نه throw.** یک هفته با سه مرحله‌ی متمایز محتوای
   * کاملاً قابل استفاده‌ای است؛ کشتنِ هفت کاروسل به‌خاطر یک معیارِ
   * توزیع، همان «چکِ قطعیِ غلط بدتر از نداشتن چک است» می‌شود — فقط
   * با هزینه‌ی هفت برابر. این معیار کیفیت است، نه درستی.
   *
   * (اگر روزی خواستی اجباری شود، جایش `.refine` روی WeeklyPlanSchema
   *  است نه throw اینجا: آن‌وقت runAgentJSON یک بار با پیام خطا دوباره
   *  تلاش می‌کند، به‌جای اینکه اجرا را بکشد.)
   */
  const stages = [...new Set(plan.slots.map((s) => s.journeyStage))];
  if (stages.length < MIN_DISTINCT_JOURNEY_STAGES) {
    const spread = plan.slots
      .map((s) => `${s.day}:${s.journeyStage}`)
      .join("، ");
    console.warn(
      `[weekly-planner] فقط ${stages.length} مرحله‌ی متمایز از سفر ` +
        `(حداقل ${MIN_DISTINCT_JOURNEY_STAGES}) — ${stages.join("، ")}. ` +
        `توزیع: ${spread}. هفته تولید می‌شود ولی یک‌نواخت است.`
    );
  }

  return plan;
}
