/**
 * مشخصات بصری اسلاید کاروسل — منبع مشترک پیش‌نمایش و رندرکننده.
 *
 * ⚠️ عمداً `server-only` ندارد. هر دو طرف می‌خوانندش: `slide-renderer.ts`
 * روی Node و `CarouselPreview.tsx` در مرورگر. اگر `server-only` بگیرد،
 * پیش‌نمایش از دسترسش خارج می‌شود و دوباره دو منبع می‌شویم — همان چیزی
 * که این فایل برای حذفش ساخته شده.
 *
 * ── چرا این فایل وجود دارد ──
 *
 * پیش‌نمایش ۲۴۰ پیکسل عرض دارد و خروجی ۱۰۸۰. اگر هر دو مقادیرشان را
 * جدا بنویسند، اولین تغییر یکی را جا می‌گذارد و پیش‌نمایش دروغ می‌گوید —
 * دقیقاً همان چیزی که اصلاً برای دیدنش ساخته شده. پس پیش‌نمایش هم از
 * همین عددها می‌خواند و فقط در `scale` ضربشان می‌کند.
 *
 * ── این طرحِ ۱۰۸۰ است، نه بزرگ‌شده‌ی قاب کوچک ──
 *
 * عددهای قبلی (پدینگ ۲۴، پدینگ پایین ۴۴) برای یک چیپ ۲۴۰ پیکسلی
 * انتخاب شده بودند. ۴۴ روی ۲۴۰ یعنی ۱۸٪ عرض؛ ضرب در ۴٫۵ می‌شد ۱۹۸ که
 * بی‌معنی است. اینجا از صفر برای بوم ۱۰۸۰×۱۳۵۰ چیده شده.
 */

/* ── بوم ─────────────────────────────────────────────────── */

/** نسبت ۴:۵ — نسبت پیشنهادی فعلی اینستاگرام برای پست فید */
export const CANVAS = { width: 1080, height: 1350 } as const;

/**
 * ناحیه‌ی امن گرید پروفایل.
 *
 * ⚠️ گرید پروفایل اینستاگرام تصویر را به ۳:۴ برش می‌زند. از یک تصویر
 * ۱۰۸۰×۱۳۵۰ عرضِ باقی‌مانده ۱۳۵۰×۳/۴ = ۱۰۱۲٫۵ است، یعنی حدود ۳۴ پیکسل
 * از **هر طرف** حذف می‌شود.
 *
 * عملاً فقط اسلاید اول در گرید دیده می‌شود، ولی قاعده روی همه اعمال
 * می‌شود: هیچ عنصر معناداری بیرون از ۱۰۱۲ مرکزی نباشد. سخت‌گیری اینجا
 * رایگان است؛ فهمیدنش بعد از انتشار نه.
 */
export const SAFE_WIDTH = 1012;
export const SAFE_INSET = Math.round((CANVAS.width - SAFE_WIDTH) / 2); // ۳۴

/* ── فاصله‌ها ────────────────────────────────────────────── */

/**
 * پدینگ افقی عمداً بسیار بزرگ‌تر از SAFE_INSET است (۹۶ در برابر ۳۴).
 * یعنی متن **ساختاراً** داخل ناحیه‌ی امن می‌ماند و لازم نیست هر بار
 * چک شود. `assertInsideSafeArea` فقط برای عناصر تزئینی است که ممکن
 * است عمداً به لبه بچسبند.
 */
export const PAD = {
  x: 96,
  top: 96,
  /** متن اینجا تمام می‌شود؛ نوار پایین برای شماره‌ی اسلاید می‌ماند */
  bottom: 168,
} as const;

/**
 * فاصله‌های داخل بلوک محتوا.
 *
 * ⚠️ کیکر عضو همین بلوک است، نه یک عنصر لنگرشده به بالای قاب.
 *
 * نسخه‌ی قبلی کیکر را از بالا لنگر می‌کرد و فقط تیتر و متن را وسط‌چین:
 * نتیجه‌اش یک فاصله‌ی **محاسبه‌شده** — نه طراحی‌شده — از حدود ۳۵۰
 * پیکسل بینشان بود که با تیتر یک‌خطی بیش از همه به چشم می‌آمد. آن
 * فاصله باقی‌مانده‌ی حساب بود، نه تصمیم.
 *
 * حالا هر سه یک واحد بصری‌اند و با هم جای می‌گیرند، پس فضای خالی بین
 * بالا و پایین تقسیم می‌شود به‌جای اینکه یک‌جا وسط بیفتد.
 *
 * ⚠️ قاعده‌ی نسبت: `kickerToHeading` هرگز کمتر از `headingToBody`
 * نباشد. کیکر یک برچسب است و اگر به تیتر بچسبد، خوانده می‌شود
 * به‌عنوان خط اول تیتر — نه برچسبِ بالای آن.
 */
export const GAP = {
  /** کیکر تا تیتر — بزرگ‌تر، چون مرز دو نقش متفاوت است */
  kickerToHeading: 48,
  /** تیتر تا متن — کوچک‌تر، چون هر دو بدنه‌ی یک حرف‌اند */
  headingToBody: 40,
} as const;

/** خط پایه‌ی شماره‌ی اسلاید، از پایین بوم */
export const COUNTER_BASELINE_FROM_BOTTOM = 72;

/* ── تایپوگرافی ──────────────────────────────────────────── */

/**
 * سه سطح، با ارتفاع خطِ **مقیاس رسمی برند** (`tailwind.config.ts`).
 *
 * ⚠️ نکته‌ای که راحت اشتباه می‌شود: قاعده‌ی «ارتفاع خط حداقل ۱٫۸ در
 * فارسی» مالِ **متن بدنه** است، نه تیتر. مقیاس خود برند این را تفکیک
 * کرده: display/headline ۱٫۴ · title ۱٫۵ · body ۱٫۸ · caption ۱٫۶.
 * تیتر ۷۲ پیکسلی با ۱٫۸ می‌شود ۱۳۰ پیکسل فاصله‌ی خط — که تیتر را از
 * هم می‌پاشد.
 *
 * پس: بدنه ۱٫۸ (قاعده‌ی برند رعایت شد — پیش‌نمایش قبلی ۱٫۷۱ بود و
 * نقضش می‌کرد)، تیتر ۱٫۴، کیکر ۱٫۶ مثل caption.
 */
export const TYPE = {
  kicker: { size: 40, weight: 500, lineHeight: 1.6 },
  heading: { size: 72, weight: 700, lineHeight: 1.4 },
  body: { size: 48, weight: 400, lineHeight: 1.8 },
  counter: { size: 32, weight: 500, lineHeight: 1.4 },
} as const;

/** حداقل ارتفاع خطِ مجاز برای متن بدنه‌ی فارسی — قاعده‌ی برندگاید */
export const MIN_BODY_LINE_HEIGHT = 1.8;

/* ── رنگ ─────────────────────────────────────────────────── */

/**
 * از توکن‌های `tailwind.config.ts`، به‌شکل hex خام.
 *
 * تیلویند در زمان اجرای Node در دسترس نیست، پس مقادیر اینجا تکرار
 * شده‌اند. عمداً همان hexهای پالت رسمی‌اند و اگر پالت عوض شد، این هم
 * باید عوض شود — چهار عدد، نه یک سیستم.
 */
export const COLOR = {
  bg: "#0E394A", // navy / pine
  fg: "#E6EEF2", // bone / mist
  accent: "#1FA795", // teal / brass
  /** ⚠️ فقط برای عنصر اقدام. قاعده‌ی سختش پایین‌تر */
  action: "#F5941F", // amber
} as const;

/** شفافیت متن‌های فرعی روی پس‌زمینه‌ی سرمه‌ای */
export const OPACITY = { body: 0.8, counter: 0.5 } as const;

/* ── نقش اسلاید ──────────────────────────────────────────── */

/**
 * نقش هر اسلاید — از جایگاهش مشتق می‌شود، نه از مدل.
 *
 * دلیلش قاعده‌ی نارنجی است (پایین‌تر): اگر نقش را مدل تعیین کند،
 * می‌تواند سه اسلاید را «اقدام» بنامد و قاعده بشکند. با اشتقاق از
 * اندیس، بیش از یک اسلاید اقدام **ممکن نیست**.
 */
export type SlideRole = "cover" | "middle" | "cta";

export function roleFor(index: number, total: number): SlideRole {
  if (index === 0) return "cover";
  if (index === total - 1) return "cta";
  return "middle";
}

/**
 * رنگ عنصر تأکید هر اسلاید.
 *
 * ⚠️ قاعده‌ی برند: نارنجی فقط برای عنصر اقدام، و **حداکثر یکی در هر
 * طرح**. اینجا با ساختار قفل شده، نه با پرامپت و نه با چک: تنها
 * اسلاید با نقش `cta` نارنجی می‌گیرد و نقش هم از اندیس می‌آید. پس
 * «دو نارنجی در یک کاروسل» حالتی است که کد نمی‌تواند تولیدش کند.
 */
export function accentFor(role: SlideRole): string {
  return role === "cta" ? COLOR.action : COLOR.accent;
}

/**
 * لنگر عمودی بلوک محتوا.
 *
 * ⚠️ نسخه‌ی اول همه را ته قاب می‌چسباند و نتیجه‌اش دو سوم بالای تصویر
 * خالی بود. برای کاور بدترین حالت است: در گرید پروفایل تصویر در اندازه‌ی
 * بندانگشتی دیده می‌شود و بلوکی که ته قاب چسبیده، «مستطیل خالی با یک
 * کلمه‌ی کوچک» خوانده می‌شود.
 *
 * (نکته‌ی رایجِ اشتباه: برش گرید **افقی** است، نه عمودی — از یک تصویر
 *  ۱۰۸۰×۱۳۵۰ عرض به ۱۰۱۲ می‌رسد و ارتفاع کامل می‌ماند. پس مشکل
 *  «بالای تصویر بریده می‌شود» نیست؛ مشکل وزن بصری در اندازه‌ی کوچک است.)
 *
 * اسلاید اقدام پایین‌لنگر می‌ماند: آخرین اسلاید است، کسی رویش مکث
 * می‌کند، و پایین‌بودن دعوت به اقدام حرکت چشم را به سمت خروج می‌برد.
 */
export type BlockAlign = "center" | "bottom";

export function blockAlignFor(role: SlideRole): BlockAlign {
  return role === "cta" ? "bottom" : "center";
}

/**
 * سهم فضای آزادِ **بالای** بلوک، در حالت وسط‌چین.
 *
 * ⚠️ عمداً ۰٫۵ نیست. مرکز نوری بالاتر از مرکز هندسی است: چشم انتظار
 * دارد وزن اصلی کمی بالاتر بنشیند، و بلوکی که دقیقاً وسط ریاضی قاب
 * است پایین‌افتاده به نظر می‌رسد. نسبت متعارف ۴۵/۵۵ است.
 *
 * ۴۵٪ بالا، ۵۵٪ پایین. روی قاب ۱۳۵۰ با بلوک ۶۰۰ پیکسلی، یعنی حدود
 * ۲۴ پیکسل جابه‌جایی به بالا — کم، ولی همان مقداری که «وسط» را از
 * «کمی افتاده» جدا می‌کند.
 *
 * ⚠️ روی حالت `bottom` اعمال نمی‌شود: آنجا لنگر خودِ لبه است و فضای
 * آزادی برای تقسیم نمی‌ماند.
 */
export const OPTICAL_TOP_SHARE = 0.45;

/**
 * مختصات بالای بلوک محتوا.
 *
 * اینجاست نه در رندرکننده، چون پیش‌نمایش هم به همان نسبت نیاز دارد
 * (هرچند با فاصله‌گذارهای flex اعمالش می‌کند). یک تعریف، دو مصرف‌کننده —
 * همان دلیلی که `blockHeightPx` اینجاست.
 */
export function blockTopPx(align: BlockAlign, blockHeight: number): number {
  const regionTop = PAD.top;
  const regionBottom = CANVAS.height - PAD.bottom;
  if (align === "bottom") return regionBottom - blockHeight;

  const free = regionBottom - regionTop - blockHeight;
  return regionTop + Math.max(0, free * OPTICAL_TOP_SHARE);
}

/**
 * ارتفاع بلوک محتوا — کیکر، تیتر و متن با فاصله‌هایشان.
 *
 * اینجاست نه در رندرکننده، چون پیش‌نمایش هم به همان قاعده نیاز دارد
 * (هرچند با flex اعمالش می‌کند). یک تعریف، دو مصرف‌کننده.
 */
export function blockHeightPx(headingLines: number, bodyLines: number): number {
  return (
    lineHeightPx("kicker") +
    GAP.kickerToHeading +
    headingLines * lineHeightPx("heading") +
    (bodyLines > 0 ? GAP.headingToBody + bodyLines * lineHeightPx("body") : 0)
  );
}

/* ── سقف طول متن ─────────────────────────────────────────── */

/**
 * سقف طول هر بخش اسلاید — یک عدد، چهار مصرف‌کننده.
 *
 * پرامپت کپی‌رایتر (تا مدل عدد را بداند)، چک قطعی در social-checks،
 * تور نجات `clampSlides` در ناشر، و حالا رندرکننده.
 *
 * از `agents/types.ts` به اینجا منتقل شد چون رندرکننده هم لازمش دارد
 * و `types.ts` سمت ایجنت‌هاست. `types.ts` همچنان re-export می‌کند تا
 * importهای موجود نشکنند.
 */
export const SLIDE_LIMITS = { kicker: 24, heading: 40, text: 140 } as const;

/* ── کمکی‌ها ─────────────────────────────────────────────── */

/** عرض قابل استفاده‌ی متن */
export const CONTENT_WIDTH = CANVAS.width - PAD.x * 2;

/** ارتفاع یک خط، برای هر سطح تایپوگرافی */
export function lineHeightPx(level: keyof typeof TYPE): number {
  return TYPE[level].size * TYPE[level].lineHeight;
}

/**
 * آیا این بازه‌ی افقی داخل ناحیه‌ی امن گرید می‌ماند؟
 *
 * رندرکننده آن را روی **جعبه‌ی متن** اجرا می‌کند. امروز همیشه پاس
 * می‌شود (پدینگ ۹۶ در برابر مرز ۳۴)، ولی اگر روزی کسی پدینگ را کم کند
 * تا متن بزرگ‌تر جا شود، بی‌صدا از لبه‌ی گرید بیرون می‌زند — و آن را
 * فقط بعد از انتشار می‌شد فهمید.
 */
export function isInsideSafeArea(x: number, width: number): boolean {
  return x >= SAFE_INSET && x + width <= CANVAS.width - SAFE_INSET;
}
